#!/usr/bin/env node
'use strict';

/**
 * sync-shared.js —— 把 packages/* 同步到每個雲函數的 node_modules/@repair/*
 *
 * 為什麼需要它：微信雲函數是獨立部署單元，上傳時只帶自己的目錄，
 * 因此 `require('../../packages/domain')` 這種相對路徑**必然失效**。
 * （詳見 docs/01-目標架構.md §5）
 *
 * 為什麼是「實體複製」而非 symlink 或 npm link：
 *   Windows 上 npm link / file: 依賴會建立 junction，打包上傳時會斷。
 *   實體複製是唯一跨平台且可在本地完整驗證的做法。
 *
 * 雜湊雙寫（§5.3.1）：
 *   - cloudfunctions/<fn>/package.json 的 repairSharedHash  → 入版控，偵測「忘記同步」
 *   - node_modules/@repair/build-manifest/index.js          → 產物，執行期自我檢查
 *
 * 用法：
 *   node scripts/sync-shared.js          同步
 *   node scripts/sync-shared.js --check  只驗證，不同步（CI / pre-commit）
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const PKG_DIR = path.join(ROOT, 'packages');
const FN_DIR = path.join(ROOT, 'cloudfunctions');
const SCOPE = '@repair';

/** 必須依依賴順序排列（被依賴者在前），同時作為循環依賴的防線 */
const ORDER = ['shared-kernel', 'domain', 'ports', 'application', 'adapters'];

/** 不進 bundle 的檔案（縮小雲函數程式碼包） */
const EXCLUDE = [/\.test\.js$/, /\.spec\.js$/, /^__tests__\//, /\.md$/, /^docs\//];

function listFiles(dir, base = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    const rel = path.relative(base, abs).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      if (EXCLUDE.some((re) => re.test(rel + '/'))) continue;
      listFiles(abs, base, out);
    } else if (entry.isFile()) {
      if (EXCLUDE.some((re) => re.test(rel))) continue;
      out.push(rel);
    }
  }
  return out.sort();
}

/** 內容雜湊：路徑 + 正規化後的內容。順序無關（已排序）。 */
function hashPackage(dir) {
  const h = crypto.createHash('sha256');
  for (const rel of listFiles(dir)) {
    h.update(rel);
    h.update('\0');
    // 正規化行尾 → Windows / Linux 開發者產出一致雜湊
    h.update(fs.readFileSync(path.join(dir, rel), 'utf8').replace(/\r\n/g, '\n'));
    h.update('\0');
  }
  return h.digest('hex');
}

function buildManifest() {
  const packages = {};
  for (const name of ORDER) {
    const dir = path.join(PKG_DIR, name);
    if (!fs.existsSync(dir)) {
      throw new Error(`缺少 packages/${name}（宣告於 ORDER 中）`);
    }
    packages[name] = hashPackage(dir);
  }
  // 總雜湊：串接各套件名與雜湊後再雜湊，避免「兩包對調」偵測不到
  const hash = crypto
    .createHash('sha256')
    .update(ORDER.map((n) => `${n}:${packages[n]}`).join('|'))
    .digest('hex');
  return { hash, packages, builtAt: new Date().toISOString() };
}

function copyPackage(name, destRoot) {
  const src = path.join(PKG_DIR, name);
  const dest = path.join(destRoot, SCOPE, name);
  fs.rmSync(dest, { recursive: true, force: true });
  for (const rel of listFiles(src)) {
    const to = path.join(dest, rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(path.join(src, rel), to); // 實體複製，非 symlink
  }
}

function manifestModule(manifest) {
  return (
    "'use strict';\n" +
    '// AUTO-GENERATED by scripts/sync-shared.js — DO NOT EDIT\n' +
    `module.exports = ${JSON.stringify(manifest, null, 2)};\n`
  );
}

/**
 * 建立「開發用」的根 node_modules/@repair/* 連結。
 *
 * 為什麼需要：雲函數靠 sync 把共享碼複製進自己的 node_modules 才能解析
 * `require('@repair/domain')`；但在**本地**跑測試或 IDE 分析時，
 * 根目錄沒有 node_modules/@repair，同樣的 require 會 MODULE_NOT_FOUND。
 *
 * 用目錄連結（Windows 用 junction，不需管理員權限）而非複製，
 * 讓本地開發永遠看到 packages/ 的最新內容，不會有第二份副本走鐘。
 *
 * 注意：`npm install` 可能會清除這些「多餘」的目錄，
 * 因此 package.json 有 postinstall 會自動重建。
 */
function ensureDevLinks() {
  const scopeDir = path.join(ROOT, 'node_modules', SCOPE);
  fs.mkdirSync(scopeDir, { recursive: true });

  let created = 0;
  for (const name of ORDER) {
    const linkPath = path.join(scopeDir, name);
    const target = path.join(PKG_DIR, name);

    try {
      const stat = fs.lstatSync(linkPath);
      if (stat.isSymbolicLink() || stat.isDirectory()) {
        let resolved = null;
        try {
          resolved = fs.realpathSync(linkPath);
        } catch {
          resolved = null;
        }
        if (resolved && path.resolve(resolved) === path.resolve(target)) continue;
        fs.rmSync(linkPath, { recursive: true, force: true });
      }
    } catch {
      /* 不存在，繼續建立 */
    }

    fs.symlinkSync(target, linkPath, process.platform === 'win32' ? 'junction' : 'dir');
    created++;
  }
  return created;
}

function checkDevLinks() {
  const missing = [];
  for (const name of ORDER) {
    const linkPath = path.join(ROOT, 'node_modules', SCOPE, name);
    try {
      if (path.resolve(fs.realpathSync(linkPath)) !== path.resolve(path.join(PKG_DIR, name))) {
        missing.push(name);
      }
    } catch {
      missing.push(name);
    }
  }
  return missing;
}

function listFunctions() {
  if (!fs.existsSync(FN_DIR)) return [];
  return fs
    .readdirSync(FN_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory() && fs.existsSync(path.join(FN_DIR, e.name, 'package.json')))
    .map((e) => e.name)
    .sort();
}

function main() {
  const checkOnly = process.argv.includes('--check');

  let manifest;
  try {
    manifest = buildManifest();
  } catch (err) {
    console.error(`✗ ${err.message}`);
    process.exit(1);
  }

  // 開發用的根目錄連結（兩個模式都要確保存在，否則本地測試會 MODULE_NOT_FOUND）
  if (checkOnly) {
    const missing = checkDevLinks();
    if (missing.length > 0) {
      console.error(`✗ 本地開發連結缺失：${missing.join(', ')}。請執行 npm run sync`);
      process.exit(1);
    }
  } else {
    const created = ensureDevLinks();
    if (created > 0) console.log(`✓ 建立 ${created} 個開發用連結（node_modules/${SCOPE}/* → packages/*）`);
  }

  const functions = listFunctions();
  if (functions.length === 0) {
    console.log('（尚無雲函數，僅計算共享碼雜湊）');
    console.log(`共享碼總雜湊 = ${manifest.hash}`);
    return;
  }

  let stale = 0;

  for (const fn of functions) {
    const fnDir = path.join(FN_DIR, fn);
    const pkgPath = path.join(fnDir, 'package.json');
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));

    if (checkOnly) {
      const ok = pkg.repairSharedHash === manifest.hash;
      if (!ok) {
        console.error(`✗ ${fn}: package.json 期望 ${pkg.repairSharedHash || '(未設定)'}，實際 ${manifest.hash}`);
        stale++;
      } else {
        // 額外檢查產物是否存在（node_modules 被 gitignore，fresh clone 後不會有）
        const produced = path.join(fnDir, 'node_modules', SCOPE, 'build-manifest', 'index.js');
        if (!fs.existsSync(produced)) {
          console.error(`✗ ${fn}: 共享碼尚未同步（缺少 node_modules/${SCOPE}/）。請執行 npm run sync`);
          stale++;
        } else {
          console.log(`✓ ${fn}`);
        }
      }
      continue;
    }

    const nm = path.join(fnDir, 'node_modules');
    fs.mkdirSync(nm, { recursive: true });
    for (const name of ORDER) copyPackage(name, nm);

    const mmDir = path.join(nm, SCOPE, 'build-manifest');
    fs.mkdirSync(mmDir, { recursive: true });
    fs.writeFileSync(path.join(mmDir, 'index.js'), manifestModule(manifest));
    fs.writeFileSync(
      path.join(mmDir, 'package.json'),
      JSON.stringify({ name: `${SCOPE}/build-manifest`, version: '0.0.0', main: 'index.js' }, null, 2) + '\n',
    );

    // 只寫入 repairSharedHash。**刻意不宣告 @repair/* 為 dependencies**：
    // 檔案已實體存在於 node_modules，Node 可直接解析；
    // 若宣告為 file: 依賴，選擇「雲端安裝依賴」時 npm 會因找不到 packages/ 而失敗。
    const next = { ...pkg, repairSharedHash: manifest.hash };
    fs.writeFileSync(pkgPath, JSON.stringify(next, null, 2) + '\n');
    console.log(`✓ ${fn} → ${manifest.hash.slice(0, 12)}`);
  }

  if (checkOnly) {
    if (stale > 0) {
      console.error(`\n${stale} 個雲函數的共享碼不同步。請執行：npm run sync`);
      process.exit(1);
    }
    console.log('\n全部同步。');
    return;
  }

  console.log(`\n完成。共享碼總雜湊 = ${manifest.hash}`);
}

main();
